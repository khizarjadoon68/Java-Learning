package Inheritance;

public class Person {
    // Properties
    private int age ;
    private String name ;

    //Methods
    public void setAge(int a){
        age =a;
    }
    public void setName(String n){
        name =n;
    }

    public int getAge(){
        return (age) ;
    }
    public String getName(){
        return (name) ;
    }
}